export type GlyphName =
  keyof typeof ART | 'redo' | 'down' | 'left' | 'right' | 'front' | 'rear' | 'armor' | 'universal';

type Bitmap = string[];

function rows(source: string): Bitmap {
  return source
    .trim()
    .split('\n')
    .map((row) => row.padEnd(12, '.').slice(0, 12));
}

function mirror(bitmap: Bitmap): Bitmap {
  return bitmap.map((row) => [...row].reverse().join(''));
}

function quarter(bitmap: Bitmap): Bitmap {
  // Clockwise quarter turn.
  const out: Bitmap = [];
  for (let y = 0; y < 12; y++) {
    let row = '';
    for (let x = 0; x < 12; x++) row += bitmap[11 - x]?.[y] ?? '.';
    out.push(row);
  }
  return out;
}

const BITMAPS = new Map<string, Bitmap>();
for (const [name, source] of Object.entries(ART)) BITMAPS.set(name, rows(source));
const up = BITMAPS.get('up')!;
BITMAPS.set('right', quarter(up));
BITMAPS.set('down', quarter(quarter(up)));
BITMAPS.set('left', quarter(quarter(quarter(up))));
BITMAPS.set('front', up);
BITMAPS.set('rear', BITMAPS.get('down')!);
BITMAPS.set('redo', mirror(BITMAPS.get('undo')!));
BITMAPS.set('armor', BITMAPS.get('defense')!);
BITMAPS.set('universal', BITMAPS.get('star')!);

const PATHS = new Map<string, string>();

/** SVG path data for a glyph: one rectangle per horizontal run of ink. */
export function glyphPath(name: GlyphName): string {
  const cached = PATHS.get(name);
  if (cached !== undefined) return cached;
  const bitmap = BITMAPS.get(name) ?? [];
  let d = '';
  bitmap.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === '#') end++;
      d += `M${x} ${y}h${end - x}v1h${x - end}z`;
      x = end;
    }
  });
  PATHS.set(name, d);
  return d;
}
