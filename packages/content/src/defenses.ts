/**
 * The twenty defenses of Section 11.6. Cost, mass and the numbers in the "defining behavior"
 * column are the seed values from the table. Passive protection is expressed as primitives
 * (`AddArmorArc`, `ModifyDamageByTag`, `ModifyImpulse`), which the damage model of Milestone C
 * consumes and the Defense score reads today. Reactive defenses declare their active
 * primitives for Milestone C.
 *
 * Armor plate (everything flagged `armorPlate`) counts against the chassis armor allowance.
 * A plate protects the arc it faces: quarter turn 0 faces forward. The two plates have a
 * `free` facing, within what their mount allows. The bumpers, the mine sweeper and the side
 * shields have a `fixed` one (front, back, front, outward). Everything else has no facing and
 * protects the side of the car its mount is on.
 */

/** Internal systems: a utility bay, the roof, or behind any armor-capable panel. */
const SYSTEM: MountCategory[] = ['UTILITY', 'ROOF', 'ARMOR'];

type DefenseRow = {
  id: string;
  displayName: string;
  price: number;
  massKg: number;
  footprint: [number, number];
  mounts: MountCategory[];
  use?: 'full' | 'shared';
  /** Defaults to `none`. */
  facing?: PartFacing;
  fixedTurn?: QuarterTurn | 'outward';
  height?: 0 | 1 | 2;
  maxPerCar?: number;
  armorPlate: boolean;
  trigger?: TriggerMode;
  behaviorId: string;
  soundKey?: string;
  description: string;
  drawback: string;
  modifiers?: PartModifier[];
  params?: PartParams;
  actions?: ActivePrimitive[];
  powerDraw?: number;
};

function defense(row: DefenseRow): AccessoryDefinition {
  const def: AccessoryDefinition = {
    id: row.id,
    displayName: row.displayName,
    category: 'defense',
    price: row.price,
    massKg: row.massKg,
    footprint: { w: row.footprint[0], h: row.footprint[1] },
    compatibleMounts: row.mounts,
    spriteKey: row.id,
    soundKey: row.soundKey ?? 'defense_plate',
    description: row.description,
    drawback: row.drawback,
    modifiers: [{ type: 'AddMass', kg: row.massKg }, ...(row.modifiers ?? [])],
    behaviorId: row.behaviorId,
    triggerMode: row.trigger ?? 'passive',
    params: { armorPlate: row.armorPlate, ...row.params },
    hardpointUse: row.use ?? 'full',
    facing: row.facing ?? 'none',
    heightLevel: row.height ?? 0,
    powerDraw: row.powerDraw ?? 0,
    heatEffect: 0,
  };
  if (row.fixedTurn !== undefined) def.fixedTurn = row.fixedTurn;
  if (row.actions) def.actions = row.actions;
  if (row.maxPerCar !== undefined) def.maxPerCar = row.maxPerCar;
  return def;
}

