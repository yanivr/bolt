import type {
  AccessoryDefinition,
  ActivePrimitive,
  MountCategory,
  PartModifier,
  PartParams,
  TriggerMode,
} from '@bolt/shared';

/**
 * The twenty utility systems of Section 11.7. Cost, mass, trigger and the numbers in the
 * "defining behavior" column are the seed values from the table. Passive utilities act
 * through primitives that the integrator applies today (cooling, generation, battery,
 * stability, slip, downforce). Manual and automatic ones declare their active primitives for
 * Milestone C. Limits follow the table's preamble: one spare wheel, two repair kits, three
 * repair units in all.
 */

/** Small boxes: a utility bay, the roof, or a rear or side mount. */
const POD: MountCategory[] = ['UTILITY', 'ROOF', 'REAR', 'LEFT', 'RIGHT'];

type UtilityRow = {
  id: string;
  displayName: string;
  price: number;
  massKg: number;
  trigger: TriggerMode;
  footprint: [number, number];
  mounts: MountCategory[];
  use?: 'full' | 'shared';
  height?: 0 | 1 | 2;
  maxPerCar?: number;
  behaviorId: string;
  soundKey?: string;
  description: string;
  drawback: string;
  modifiers?: PartModifier[];
  params?: PartParams;
  actions?: ActivePrimitive[];
  /** Sustained draw and heat effect for the part card. Negative heat cools. */
  powerDraw?: number;
  heatEffect?: number;
};

function utility(row: UtilityRow): AccessoryDefinition {
  const def: AccessoryDefinition = {
    id: row.id,
    displayName: row.displayName,
    category: 'utility',
    price: row.price,
    massKg: row.massKg,
    footprint: { w: row.footprint[0], h: row.footprint[1] },
    compatibleMounts: row.mounts,
    spriteKey: row.id,
    soundKey: row.soundKey ?? 'utility_generic',
    description: row.description,
    drawback: row.drawback,
    modifiers: [{ type: 'AddMass', kg: row.massKg }, ...(row.modifiers ?? [])],
    behaviorId: row.behaviorId,
    triggerMode: row.trigger,
    params: { ...row.params },
    hardpointUse: row.use ?? 'shared',
    rotatable: false,
    heightLevel: row.height ?? 0,
    powerDraw: row.powerDraw ?? 0,
    heatEffect: row.heatEffect ?? 0,
  };
  if (row.actions) def.actions = row.actions;
  if (row.maxPerCar !== undefined) def.maxPerCar = row.maxPerCar;
  return def;
}

