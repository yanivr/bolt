import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { ENGINE_LOUDNESS, LOUDNESS_TARGETS } from '../../apps/web/src/game/audio/recipe.js';
import type { Category } from '../../apps/web/src/game/audio/recipe.js';
import { dB, loudestWindow, rms } from './analysis.js';
import {
  ENGINE_RUN,
  engineKeys,
  openHarness,
  recipeInfo,
  renderEngine,
  renderRecipe,
} from './harness.js';

/**
 * Level calibration. Every recipe is rendered alone through the master chain and its gain is
 * moved until its loudest 100 ms sits on its category's target; every engine likewise, on its
 * second at full throttle. The result is written to `apps/web/src/game/audio/sfxTrim.ts`.
 *
 *   pnpm build
 *   PORT=2671 node apps/server/dist/main.js &
 *   BOLT_E2E_PORT=2671 npx tsx tests/audio/calibrate.ts
 *   pnpm build        (the table is compiled into the client)
 *
 * Run it after changing a recipe's layers or its category. The render test fails when a
 * sound has drifted out of its window, which is the reminder.
 */

const port = Number(process.env.BOLT_E2E_PORT ?? 2567);
const out = fileURLToPath(new URL('../../apps/web/src/game/audio/sfxTrim.ts', import.meta.url));

const browser = await chromium.launch();
const page = await browser.newPage({ baseURL: `http://localhost:${port}` });
await openHarness(page);

const sfx: Record<string, number> = {};
for (const info of await recipeInfo(page)) {
  const aim = LOUDNESS_TARGETS[info.cat as Category].aim;
  const raw = await renderRecipe(page, info.id, { raw: true });
  const rawDb = dB(loudestWindow(raw.channels[0]!, raw.rate));
  let trim = Math.pow(10, (aim - rawDb) / 20);
  let measured = rawDb;
  // The compressor answers a louder input with less than as much more output, so step in.
  for (let pass = 0; pass < 6; pass++) {
    const clip = await renderRecipe(page, info.id, { trim });
    measured = dB(loudestWindow(clip.channels[0]!, clip.rate));
    if (Math.abs(measured - aim) < 0.25) break;
    trim *= Math.pow(10, Math.max(-6, Math.min(6, aim - measured)) / 20);
  }
  sfx[info.id] = Number(trim.toFixed(4));
  console.log(
    `${info.id.padEnd(24)} ${info.cat.padEnd(13)} raw ${rawDb.toFixed(1).padStart(6)}  trim ${trim.toFixed(3).padStart(7)}  -> ${measured.toFixed(1)} dBFS (aim ${aim})`,
  );
}

const engines: Record<string, number> = {};
for (const key of await engineKeys(page)) {
  const window = (clip: { channels: Float32Array[]; rate: number }) =>
    dB(
      rms(
        clip.channels[0]!,
        Math.round(ENGINE_RUN.pullEnd * clip.rate),
        Math.round(ENGINE_RUN.holdEnd * clip.rate),
      ),
    );
  let trim = 1;
  let measured = 0;
  for (let pass = 0; pass < 6; pass++) {
    measured = window(await renderEngine(page, key, { trim }));
    if (Math.abs(measured - ENGINE_LOUDNESS.aim) < 0.25) break;
    trim *= Math.pow(10, Math.max(-12, Math.min(12, ENGINE_LOUDNESS.aim - measured)) / 20);
  }
  engines[key] = Number(trim.toFixed(4));
  console.log(
    `${key.padEnd(24)} trim ${trim.toFixed(3).padStart(7)}  -> ${measured.toFixed(1)} dBFS at full throttle (aim ${ENGINE_LOUDNESS.aim})`,
  );
}
await browser.close();

const table = (name: string, values: Record<string, number>) =>
  `export const ${name}: Readonly<Record<string, number>> = {\n${Object.entries(values)
    .map(([key, value]) => `  ${key}: ${value},`)
    .join('\n')}\n};\n`;

writeFileSync(
  out,
  `/**
 * GENERATED by the audio calibration (\`npx tsx tests/audio/calibrate.ts\`, see
 * docs/AUDIO_GUIDE.md). Do not edit by hand: change the recipe or its category and calibrate
 * again. Each number is the gain that puts a sound on its category's loudness target.
 */
${table('SFX_TRIM', sfx)}
${table('ENGINE_TRIM', engines)}`,
);
console.log(`wrote ${out}`);
