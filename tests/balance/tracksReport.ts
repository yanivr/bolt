import {
  DEFAULT_LOADOUT,
  RIVAL_TEMPLATES,
  TIRE_LIST,
  TRACKS,
  getWeatherPreset,
  resolveLoadout,
} from '@bolt/content';
import { TOW, buildTrack } from '@bolt/shared';
import type { BalanceReport } from './harness.js';
import { WIN_RATE_HIGH, WIN_RATE_LOW, courseId, runBalance } from './harness.js';
import { driveDefaultCar } from '../helpers/trackDrive.js';

/**
 * The balance harness on all eight tracks and both of each track's weathers (Milestone D):
 * every shipped build against every other from both grid slots, sparring brain against
 * sparring brain, tow on, and a tire study: the default car with each wheel kit driven alone
 * over the default route, which is where surface choice shows up in a lap time.
 *
 *   npx tsx tests/balance/tracksReport.ts [seeds] > docs/evidence/balance/tracks-0.7.0.md
 */

const count = Math.max(1, Number(process.argv[2] ?? 1));
const seeds = Array.from({ length: count }, (_, i) => 1001 + i * 7919);
const started = Date.now();
const pct = (v: number) => `${(v * 100).toFixed(0)}%`;
const f = (v: number, d = 1) => v.toFixed(d);

console.log('# Balance on all eight tracks (catalog 0.7.0)\n');
console.log(
  `Generated by \`npx tsx tests/balance/tracksReport.ts ${count}\`. Seeds ${seeds.join(', ')}; ` +
    `${RIVAL_TEMPLATES.length} shipped builds, every one against every other from both grid slots on every ` +
    `course (${RIVAL_TEMPLATES.length * (RIVAL_TEMPLATES.length - 1) * seeds.length} races a course), sparring brain in both cars, tow on ` +
    `(${TOW.thresholdGap} s to ${TOW.fullGap} s, ${pct(TOW.maxBonus)}). The sparring brain drives the main route and never a shortcut: ` +
    'the shortcuts are for players and for the Milestone D AI. Win rates compare builds, not drivers.\n',
);

type Row = { course: string; name: string; weather: string; report: BalanceReport };
const rows: Row[] = [];
for (const def of Object.values(TRACKS))
  for (const presetId of def.weatherPresetIds) {
    const report = runBalance(seeds, courseId(def.id, presetId), RIVAL_TEMPLATES, true);
    rows.push({
      course: `${def.id}/${presetId}`,
      name: def.name,
      weather: getWeatherPreset(presetId)!.displayName,
      report,
    });
  }

console.log('## Every course\n');
console.log(
  '| Track | Weather | Races | Mean race s | Finish / timeout / KO | Lap 1 leader wins | Within 220 px a race, s | Damage a race | Builds outside 30 to 70% | Best build | Worst build |',
);
console.log('| :-- | :-- | --: | --: | :-- | --: | --: | --: | --: | :-- | :-- |');
for (const r of rows) {
  const t = r.report;
  const sorted = [...t.templates].sort((a, b) => b.winRate - a.winRate);
  const outside = t.templates.filter(
    (x) => x.winRate > WIN_RATE_HIGH || x.winRate < WIN_RATE_LOW,
  ).length;
  console.log(
    `| ${r.name} | ${r.weather} | ${t.matches} | ${f(t.meanRaceSeconds)} | ${t.reasons['finish'] ?? 0} / ${t.reasons['timeout'] ?? 0} / ${t.reasons['ko'] ?? 0} | ` +
      `${pct(t.racing.lap1LeaderWins)} | ${f(t.racing.reachSecondsPerRace)} | ${f(t.racing.damagePerRace)} | ${outside} | ` +
      `${sorted[0]!.name} ${pct(sorted[0]!.winRate)} | ${sorted[sorted.length - 1]!.name} ${pct(sorted[sorted.length - 1]!.winRate)} |`,
  );
}

console.log('\n## Win rate of each build on each course\n');
const names = RIVAL_TEMPLATES.map((t) => t.id);
console.log(`| Course | ${rows[0]!.report.templates.map((t) => t.name).join(' | ')} |`);
console.log(`| :-- |${names.map(() => ' --: |').join('')}`);
for (const r of rows) {
  const byId = new Map(r.report.templates.map((t) => [t.id, t]));
  console.log(
    `| ${r.name}, ${r.weather} | ${rows[0]!.report.templates.map((t) => pct(byId.get(t.id)?.winRate ?? 0)).join(' | ')} |`,
  );
}

console.log(
  '\n## Surface choice: the default car with each wheel kit, alone, over the default route\n',
);
console.log(
  'Baseline Beetle and Four-Cylinder, the centerline driver, race time in seconds (three laps). The fastest kit on each course is in bold. Kits that did not finish in 180 s are marked DNF.\n',
);
const kits = TIRE_LIST.map((t) => t.id);
console.log(`| Course | ${TIRE_LIST.map((t) => t.displayName).join(' | ')} |`);
console.log(`| :-- |${kits.map(() => ' --: |').join('')}`);
for (const def of Object.values(TRACKS))
  for (const presetId of def.weatherPresetIds) {
    const track = buildTrack(def);
    const times = kits.map((kit) => {
      const r = resolveLoadout({ ...DEFAULT_LOADOUT, tireKitId: kit });
      if (!r.ok) return null;
      const run = driveDefaultCar(track, presetId, r.params);
      return run.finished ? run.raceSeconds : null;
    });
    const best = Math.min(...times.map((t) => t ?? Infinity));
    console.log(
      `| ${def.name}, ${getWeatherPreset(presetId)!.displayName} | ${times
        .map((t) => (t === null ? 'DNF' : t === best ? `**${f(t)}**` : f(t)))
        .join(' | ')} |`,
    );
  }

console.log(`\n${((Date.now() - started) / 1000).toFixed(0)} s to generate.`);
